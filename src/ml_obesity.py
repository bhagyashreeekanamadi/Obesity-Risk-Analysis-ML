plt.title("Actual vs Predicted Weight")

plt.show()

"""## 7.2 Ridge Regression

Ridge Regression is a regularized version of Linear Regression.

It adds an L2 regularization penalty to reduce the impact of large model coefficients and can help control model complexity.

The regularization strength is controlled using `alpha`.
"""

