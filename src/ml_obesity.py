"""# 9. Unsupervised Learning — K-Means Clustering

## Objective

Use K-Means clustering to discover groups of individuals based on demographic, lifestyle, activity, and related features.

No target variable is used when creating the clusters.

`NObeyesdad` and `Weight` are excluded from the clustering input.
"""

X_cluster = df.drop(columns=['NObeyesdad', 'Weight'])

numeric_features = [
    'Age',
    'Height',
    'FCVC',
    'NCP',
    'CH2O',
    'FAF',
    'TUE',
    'BMI',
    'lifestyle_score',
    'activity_hydration_ratio'
]

categorical_features = [
    'Gender',
    'family_history_with_overweight',
    'FAVC',
    'CAEC',
    'SMOKE',
    'SCC',
    'CALC',
    'MTRANS'
]

"""### Clustering Preprocessing

Numerical features are standardized using `StandardScaler`.

Categorical features are converted using `OneHotEncoder`.

This creates a numerical feature matrix suitable for K-Means clustering.
"""

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder

preprocessor_cluster = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numeric_features),
        ('cat', OneHotEncoder(handle_unknown='ignore'), categorical_features)
    ]
)

X_processed = preprocessor_cluster.fit_transform(X_cluster)

X_processed.shape

"""## 9.1 K-Means Clustering

K-Means divides observations into a predefined number of clusters.

Each observation is assigned to the cluster with the nearest centroid.

An initial configuration of 4 clusters is used.
"""

from sklearn.cluster import KMeans

kmeans = KMeans(
    n_clusters=4,
    random_state=42,
    n_init=10
)

cluster_labels = kmeans.fit_predict(X_processed)

df['Cluster'] = cluster_labels

df['Cluster'].value_counts().sort_index()

"""## 9.2 Elbow Method

The Elbow Method evaluates different values of K using K-Means inertia.

Inertia measures the sum of squared distances between observations and their assigned cluster centroids.

The resulting curve can help identify a suitable number of clusters.
"""

import matplotlib.pyplot as plt

inertia = []

for k in range(2, 11):

    kmeans = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    kmeans.fit(X_processed)

    inertia.append(kmeans.inertia_)

plt.figure(figsize=(8,5))

plt.plot(range(2,11), inertia, marker='o')

plt.xlabel('Number of Clusters (K)')
plt.ylabel('Inertia')
plt.title('Elbow Method')

plt.show()

"""## 9.3 Silhouette Score

Calculate the Silhouette Score for different numbers of clusters.

The Silhouette Score measures how similar an observation is to its own cluster compared with other clusters.

It provides an additional measure for assessing cluster separation.
"""

from sklearn.metrics import silhouette_score

silhouette_scores = []

for k in range(2, 11):

    kmeans = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    labels = kmeans.fit_predict(X_processed)

    score = silhouette_score(X_processed, labels)

    silhouette_scores.append(score)

plt.figure(figsize=(8,5))

plt.plot(
    range(2,11),
    silhouette_scores,
    marker='o'
)

plt.xlabel('Number of Clusters (K)')
plt.ylabel('Silhouette Score')
plt.title('Silhouette Score for Different K')

plt.show()

"""## 9.4 Final K-Means Clustering

Apply the selected number of clusters and assign each observation to its final cluster.

The cluster labels are stored in the `Cluster` column.
"""

kmeans_final = KMeans(
    n_clusters=4,
    random_state=42,
    n_init=10
)

df['Cluster'] = kmeans_final.fit_predict(X_processed)

df['Cluster'].value_counts().sort_index()

